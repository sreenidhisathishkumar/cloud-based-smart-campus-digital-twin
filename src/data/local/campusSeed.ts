export function facilityCountsFor(buildingId: string, list: Facility[] = facilities) {
  const inBuilding = list.filter((item) => item.buildingId === buildingId)
  return {
    rooms: inBuilding.filter((item) => item.type === 'room').length,
    labs: inBuilding.filter((item) => item.type === 'lab').length,
    facilities: inBuilding.filter((item) => item.type === 'facility').length,
  }
}

export const buildings: Building[] = buildingRecords.map((building) => ({
  ...building,
  facilityCounts: facilityCountsFor(building.id),
}))

export function buildCampusOverview(list: Building[]): CampusOverview {
  return {
    name: CAMPUS_NAME,
    tagline: 'Live digital twin of campus buildings, facilities, and operations',
    totalBuildings: list.length,
    operationalBuildings: list.filter((b) => b.status === 'operational').length,
    maintenanceBuildings: list.filter((b) => b.status === 'maintenance').length,
    totalFacilities: list.reduce(
      (sum, b) =>
        sum + b.facilityCounts.rooms + b.facilityCounts.labs + b.facilityCounts.facilities,
      0,
    ),
  }
}

